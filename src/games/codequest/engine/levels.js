// `index` es 0-based (para arrays) y `number` es 1-based (lo que ve el estudiante y se guarda en la BD)
export const LEVELS = RAW.map((l, index) => ({ ...l, index, number: index + 1 }))

export const LEVEL_COUNT = LEVELS.length

// Texto "Debes usar: ... · Máximo N caracteres."
export function requirementText(level) {
  const need = (level.need || []).map((k) => NEED_TEXT[k]).filter(Boolean)
  let s = need.length ? 'Debes usar: ' + need.join(', ') : 'Usa los botones de abajo para escribir tu código'
  if (level.max) s += ' · Máximo ' + level.max + ' caracteres'
  return s + '.'
}
